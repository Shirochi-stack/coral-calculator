def add(name, table):
    path = ROOT / "tools" / "cutscenes" / f"{name}.json"
    spec = json.loads(path.read_text(encoding="utf-8"))
    n = len(spec["lines"])
    tongues = {}
    for lang, lines in table.items():
        if len(lines) != n:
            raise SystemExit(f"{name} {lang}: {len(lines)} lines for {n}")
        tongues[lang] = {"lines": lines, "says": SAYS[lang]}
    spec["tongues"] = tongues
    path.write_text(json.dumps(spec, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(name, "tongues added:", list(tongues))


