"""
Sound effects for the clips (v5), synthesised here with numpy: every sound is generated by this file (noise, filters, decaying partials, chirps), so there is no
sample licence to carry: they are original, free to use in the game. Each is chosen for what is on screen (ink: wet launch, splash, splat; swings: whooshes;
bats: wooden crack; books and pages: thud, flap, rustle; beams and hearts: shimmer; slimes: squelch; blades: metal shing).

    library()  -> {name: float32 mono array at 48 kHz, peak about -3 dBFS}
    CUES       -> {clip number: [(second, name, dB)]} timed to the frame of the visible action (checked against the frames)
    SOURCES    -> {name: where it comes from}
"""
import numpy
import scipy.signal

RATE = 48000
rng = numpy.random.default_rng(20261128)


def t_(d):
    return numpy.arange(int(d * RATE)) / RATE


def noise(d):
    return rng.standard_normal(int(d * RATE)).astype("float32")


def bp(x, lo, hi, order=2):
    return scipy.signal.sosfilt(scipy.signal.butter(order, [lo, hi], "bandpass", fs=RATE, output="sos"), x).astype("float32")


def lp(x, f, order=2):
    return scipy.signal.sosfilt(scipy.signal.butter(order, f, "low", fs=RATE, output="sos"), x).astype("float32")


def hp(x, f, order=2):
    return scipy.signal.sosfilt(scipy.signal.butter(order, f, "high", fs=RATE, output="sos"), x).astype("float32")


def expo(d, tau, attack=.004):
    t = t_(d)
    return (numpy.minimum(1, t / attack) * numpy.exp(-t / tau)).astype("float32")


def swell(d, peak, a=.3, b=.35):
    """Rises to its peak at fraction `peak` of the duration and falls."""
    t = t_(d) / d
    return numpy.where(t < peak, (t / peak) ** (1 / a), ((1 - t) / (1 - peak)) ** (1 / b)).astype("float32")


def norm(x, db=-3):
    return (x / (numpy.abs(x).max() + 1e-9) * 10 ** (db / 20)).astype("float32")


def chirp(d, f0, f1, tau):
    t = t_(d)
    f = f0 * (f1 / f0) ** (t / d)
    return (numpy.sin(2 * numpy.pi * numpy.cumsum(f) / RATE) * numpy.exp(-t / tau)).astype("float32")


def place(base, x, at, gain=1.0):
    s = int(at * RATE)
    if s >= len(base):
        return
    seg = x[: len(base) - s] * gain
    base[s:s + len(seg)] += seg


def droplets(d, n, f_lo=500, f_hi=2200, decay=2.0):
    out = numpy.zeros(int(d * RATE), dtype="float32")
    for _ in range(n):
        at = d * rng.random() ** decay
        f = f_lo + (f_hi - f_lo) * rng.random()
        place(out, chirp(.06, f * 1.3, f * .7, .02), at, .2 + .5 * rng.random())
    return out


def whoosh(d, lo, hi, peak=.45):
    n = noise(d)
    parts = bp(n, lo, hi) * swell(d, peak) + .6 * bp(n, lo * .4, hi * .5) * swell(d, peak + .1)
    return norm(parts)


def ink_launch():
    d = .75
    n = noise(d)
    body = lp(n, 1400) * swell(d, .7, .6, .3)
    body += .5 * bp(n, 300, 900) * swell(d, .6)
    pops = droplets(d, 14, 350, 1400, 1.0) * swell(d, .6)
    return norm(body + pops * .8)


def ink_splash():
    d = 1.1
    n = noise(d)
    burst = lp(n, 3500) * expo(d, .16, .002) + .7 * bp(n, 800, 5000) * expo(d, .08, .002)
    thump = chirp(.3, 140, 55, .09) * .8
    out = burst
    place(out, thump, 0)
    out += droplets(d, 26, 600, 2800, 1.8) * .8
    return norm(out)


def ink_splat():
    d = .5
    n = noise(d)
    slap = bp(n, 500, 2800) * expo(d, .05, .001)
    thud = chirp(.25, 120, 50, .07)
    out = slap * .9
    place(out, thud, 0, 1.0)
    out += droplets(d, 5, 700, 2000, 1.0) * .7
    return norm(out)


def ink_wave():
    d = 1.4
    n = noise(d)
    out = lp(n, 1800) * swell(d, .35, .6, .6) + .5 * bp(n, 200, 700) * swell(d, .5)
    out += droplets(d, 22, 400, 1600, 1.3) * .5
    return norm(out)


def drips():
    d = 1.2
    out = droplets(d, 12, 700, 2400, 1.0)
    out += .3 * lp(noise(d), 900) * expo(d, .5)
    return norm(out)


def squelch():
    d = .55
    t = t_(d)
    f = 110 + 220 * numpy.sin(2 * numpy.pi * (3 + 6 * t) * t) ** 2 + 120 * t
    out = numpy.sin(2 * numpy.pi * numpy.cumsum(f) / RATE) * expo(d, .18, .01)
    out += .4 * lp(noise(d), 1500) * expo(d, .12)
    out += droplets(d, 6, 300, 900, 1.0) * .5
    return norm(out)


def slime_pop():
    return norm(chirp(.12, 900, 250, .03) + .4 * bp(noise(.12), 400, 1800) * expo(.12, .03))


def water_splash_big():
    d = 1.6
    n = noise(d)
    out = lp(n, 4000) * expo(d, .3, .003) + .6 * bp(n, 1000, 6000) * expo(d, .15, .002)
    place(out, chirp(.5, 110, 40, .15), 0, 1.2)
    out += droplets(d, 40, 500, 3000, 1.6)
    return norm(out)


def wood_crack():
    d = .6
    click = noise(.01) * numpy.hanning(int(.01 * RATE))
    out = numpy.zeros(int(d * RATE), dtype="float32")
    place(out, click, 0, 1.0)
    for f, tau, g in ((620, .09, .8), (1240, .06, .6), (2150, .04, .4), (180, .12, .9)):
        place(out, numpy.sin(2 * numpy.pi * f * t_(.5)) * numpy.exp(-t_(.5) / tau), 0, g)
    out += .5 * bp(noise(d), 1500, 6000) * expo(d, .015, .001)
    return norm(out)


def wood_tap():
    d = .3
    out = numpy.zeros(int(d * RATE), dtype="float32")
    for f, tau, g in ((420, .05, 1.0), (900, .03, .5)):
        place(out, numpy.sin(2 * numpy.pi * f * t_(.25)) * numpy.exp(-t_(.25) / tau), 0, g)
    return norm(out, -8)


def paper_rustle(d=1.0):
    n = hp(noise(d), 1800)
    am = numpy.abs(lp(noise(d), 40)) ** 1.5
    am = am / am.max()
    return norm(n * am * swell(d, .4, .7, .7))


def page_flap():
    d = .45
    n = bp(noise(d), 700, 4000)
    flutter = (.6 + .4 * numpy.sin(2 * numpy.pi * 38 * t_(d))) * expo(d, .12, .005)
    return norm(n * flutter)


def paper_burst():
    d = 1.2
    out = paper_rustle(d) * .9
    place(out, hp(noise(.2), 2500) * expo(.2, .05, .002), 0, .8)
    return norm(out)


def book_thud():
    d = .55
    out = numpy.zeros(int(d * RATE), dtype="float32")
    place(out, chirp(.4, 85, 38, .12), 0, 1.0)
    place(out, lp(noise(d), 260) * expo(d, .08, .002), 0, .5)
    place(out, bp(noise(.05), 800, 3000) * expo(.05, .01, .001), 0, .4)
    return norm(out)


def soft_thud():
    return norm(chirp(.3, 100, 50, .07), -6)


def impact_hit():
    d = .55
    out = numpy.zeros(int(d * RATE), dtype="float32")
    place(out, chirp(.35, 150, 45, .1), 0, 1.0)
    place(out, bp(noise(.12), 900, 5000) * expo(.12, .025, .001), 0, .8)
    return norm(out)


def explosion():
    d = 1.8
    n = noise(d)
    out = lp(n, 1200) * expo(d, .45, .004) + .5 * bp(n, 2000, 7000) * expo(d, .12, .002)
    place(out, chirp(.9, 70, 28, .3), 0, 1.3)
    return norm(out)


def shimmer(d=1.5, base=1800, n=14):
    out = numpy.zeros(int(d * RATE), dtype="float32")
    for _ in range(n):
        f = base * (1 + 3 * rng.random())
        at = d * .6 * rng.random()
        tau = .15 + .5 * rng.random()
        part = numpy.sin(2 * numpy.pi * f * t_(1.2)) * numpy.exp(-t_(1.2) / tau)
        part += .4 * numpy.sin(2 * numpy.pi * f * 2.01 * t_(1.2)) * numpy.exp(-t_(1.2) / (tau * .6))
        place(out, part.astype("float32"), at, .3 + .7 * rng.random())
    out *= (1 + .25 * numpy.sin(2 * numpy.pi * 6 * t_(d)))
    return norm(out, -6)


def heart_sparkle():
    d = 1.0
    out = shimmer(d, 2400, 10)
    for k, f in enumerate((1568, 1976, 2349, 3136)):
        place(out, numpy.sin(2 * numpy.pi * f * t_(.5)) * numpy.exp(-t_(.5) / .18), .08 * k, .35)
    return norm(out, -6)


def beam(d=2.6):
    t = t_(d)
    hum = numpy.sin(2 * numpy.pi * (95 + 80 * (t / d)) * t) + .5 * numpy.sin(2 * numpy.pi * (190 + 160 * (t / d)) * t)
    roar = bp(noise(d), 300, 3500) * (.3 + .7 * t / d)
    out = (hum * .5 + roar * .8) * swell(d, .7, .5, .25)
    out += .35 * shimmer(d, 2200, 12)[: len(out)]
    return norm(out)


def beam_burst():
    d = 2.0
    out = beam(d) * .9
    place(out, explosion()[: int(1.2 * RATE)], .15, .5)
    return norm(out)


def metal_shing(d=1.0):
    out = bp(noise(.4), 4000, 12000) * expo(.4, .08, .001)
    full = numpy.zeros(int(d * RATE), dtype="float32")
    place(full, out, 0, .7)
    for f, tau, g in ((3100, .35, .7), (4650, .28, .6), (6700, .2, .5), (8900, .15, .35)):
        place(full, numpy.sin(2 * numpy.pi * f * t_(.9)) * numpy.exp(-t_(.9) / tau), 0, g)
    return norm(full, -6)


def glass_crack():
    d = 1.4
    out = numpy.zeros(int(d * RATE), dtype="float32")
    for _ in range(26):
        at = d * rng.random() ** 1.6
        place(out, bp(noise(.01), 2500, 9000) * numpy.hanning(int(.01 * RATE)), at, .3 + .7 * rng.random())
    place(out, metal_shing(.8) * .4, 0)
    return norm(out, -6)


def zero_rise():
    d = 2.8
    t = t_(d)
    hum = numpy.sin(2 * numpy.pi * (55 + 40 * (t / d) ** 2) * t) + .4 * numpy.sin(2 * numpy.pi * (110 + 80 * (t / d) ** 2) * t)
    out = hum * swell(d, .75, .6, .3) + .5 * shimmer(d, 1500, 16)[: len(t)]
    return norm(out)


def cloth(d=.5):
    return norm(lp(noise(d), 2500) * swell(d, .4, .6, .6) * .8 + .3 * bp(noise(d), 300, 800) * swell(d, .5), -8)


def wing_flap():
    d = .7
    n = lp(noise(d), 1800) * (.5 + .5 * numpy.sin(2 * numpy.pi * 7 * t_(d))) ** 2 * swell(d, .4, .6, .5)
    return norm(n, -6)


def bread_thump():
    out = chirp(.3, 180, 70, .06)
    place(out, bp(noise(.15), 300, 1500) * expo(.15, .04), 0, .4)
    return norm(out, -6)


def dust_poof():
    d = .9
    return norm(lp(noise(d), 1200) * swell(d, .25, .5, .6), -8)


def rumble():
    d = 1.6
    return norm(lp(noise(d), 160, 3) * swell(d, .5, .7, .7), -6)


def wind(d=6.0):
    n = lp(noise(d), 700) * (.6 + .4 * lp(noise(d), 1.5) / (numpy.abs(lp(noise(d), 1.5)).max() + 1e-9))
    return norm(n, -14)


