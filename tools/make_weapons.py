"""Writes RunWeaponData.java from tools/weapons_table.py and the icons' measured handle and tip (tools/economy_art.py writes weapon_axes.json).

usage: python tools/make_weapons.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import weapons_table as T  # noqa: E402

ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "app", "src", "main", "java", "com", "coral", "calculator", "RunWeaponData.java")
AXES = os.path.join(ROOT, "assets", "economy", "weapon_axes.json")


def q(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    rows = T.ROWS
    axes = json.load(open(AXES)) if os.path.exists(AXES) else [[0, 0, 0, 0]] * len(rows)
    out = ["package com.coral.calculator;", "", "/** GENERATED by tools/make_weapons.py from tools/weapons_table.py: do not edit. The named weapons, in the order of their pictures. */",
           "final class RunWeaponData {", "    private RunWeaponData() {}", ""]
    out.append("    static final int COUNT = %d;" % len(rows))
    out.append("    static final String[] NAMES = {" + ", ".join(q(r[1]) for r in rows) + "};")
    out.append("    static final String[] LOOKS = {" + ", ".join(q(r[9][0].upper() + r[9][1:] + ".") for r in rows) + "};")
    out.append("    /** The class of each (an index of RunLoot.WEAPONS), its chapter (the theme), the rarest and the least rare it is found as. */")
    for name, idx in (("KIND", 0), ("ERA", 2), ("LOW", 3), ("HIGH", 4), ("POWER", 5), ("REACH", 6), ("REST", 7)):
        out.append("    static final int[] %s = {" % name + ", ".join(str(r[idx]) for r in rows) + "};")
    out.append("    /** What each does besides: effect and its figure at white, in pairs (RunLoot's effects). */")
    out.append("    static final int[][] EFFECTS = {")
    for r in rows:
        out.append("        {" + ", ".join("%d, %d" % (T.EFFECT_IDS[e], f) for e, f in r[8]) + "},")
    out.append("    };")
    out.append("    /** The handle and the tip of each picture, in its square of 128: x, y, x, y. */")
    out.append("    static final short[][] AXES = {")
    for a in axes:
        out.append("        {%d, %d, %d, %d}," % tuple(a))
    out.append("    };")
    out.append("}")
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print("wrote", len(rows), "weapons")


if __name__ == "__main__":
    main()
